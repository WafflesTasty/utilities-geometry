package waffles.utils.geom.utilities;

/**
 * A {@code Dimensional} object defines a spatial dimension.
 *
 * @author Waffles
 * @since 08 Sep 2024
 * @version 1.1
 */
@FunctionalInterface
public interface Dimensional
{
	/**
	 * Returns a spatial dimension.
	 * 
	 * @return a spatial dimension
	 */
	public abstract int Dimension();
}